#!/usr/bin/env bash
# Adapt SFT settings to the shared train/eval/checkpoint driver.
set -euo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

export SFT_TRAIN_SEGMENT=true
for option in TOTAL_TRAINING_STEPS CHECKPOINT_EVAL_INTERVAL EXPERIMENT_NAME PROJECT_NAME LOGGER \
  CHECKPOINT_EVAL_GEN_DIR \
  CHECKPOINT_EVAL_PROMPT_FILE CHECKPOINT_EVAL_TEST_FILE CHECKPOINT_EVAL_NGPUS_PER_NODE \
  EARLY_STOP_PATIENCE CATASTROPHIC_DROP MINIMUM_OUTPUT_COVERAGE TARGET_ROUGE_1 \
  MINIMUM_ROUGE_2 MINIMUM_ROUGE_L RUN_CHECKPOINT_EVAL KEEP_BEST_CHECKPOINT; do
  sft_key="SFT_${option}"
  if [[ -n "${!sft_key:-}" ]]; then
    export "SINGLE_WISE_DPO_${option}=${!sft_key}"
  fi
done
export SINGLE_WISE_DPO_CKPT_DIR="${SFT_DEFAULT_LOCAL_DIR}"
export SINGLE_WISE_DPO_PYTHON_BIN="${SFT_PYTHON_BIN}"
export SINGLE_WISE_DPO_TRAIN_SCRIPT="${SCRIPT_DIR}/run_pens_sft.sh"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_MODEL_LEAF=hf_merged
export SINGLE_WISE_DPO_INTERLEAVED_DRY_RUN="${SFT_INTERLEAVED_DRY_RUN:-${SFT_DRY_RUN:-false}}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_SCRIPT="${SFT_CHECKPOINT_EVAL_SCRIPT:-recipe/dpo/evaluation/run_pens_personalized_eval.sh}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_GEN_TP="${SFT_CHECKPOINT_EVAL_GEN_TP:-1}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_NNODES="${SFT_CHECKPOINT_EVAL_NNODES:-1}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_THINKING_MODE="${SFT_CHECKPOINT_EVAL_THINKING_MODE:-false}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_STATE_FILE="${SFT_CHECKPOINT_EVAL_STATE_FILE:-${SFT_DEFAULT_LOCAL_DIR}/interleaved_eval_state.json}"
exec bash "${SCRIPT_DIR}/run_single_wise_interleaved_eval.sh" "$@"
