#!/usr/bin/env bash
set -euxo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../../.." && pwd)"
cd "${REPO_ROOT}"
source "${SCRIPT_DIR}/common.sh"

# Local scratch paths and single-node topology. Every value remains overridable
# from the environment for ad-hoc runs.
export SINGLE_WISE_DPO_DATA_ROOT="${SINGLE_WISE_DPO_DATA_ROOT:-${PENS_DPO_DATA_ROOT}}"
export SINGLE_WISE_DPO_MODEL_DIR="${SINGLE_WISE_DPO_MODEL_DIR:-${PENS_MODEL_DIR}}"
export SINGLE_WISE_DPO_TOKENIZER_PATH="${SINGLE_WISE_DPO_TOKENIZER_PATH:-${SINGLE_WISE_DPO_MODEL_DIR}}"
export SINGLE_WISE_DPO_CKPT_ROOT="${SINGLE_WISE_DPO_CKPT_ROOT:-${PENS_CKPT_ROOT}}"
export SINGLE_WISE_DPO_PYTHON_BIN="${SINGLE_WISE_DPO_PYTHON_BIN:-${PENS_PYTHON_BIN}}"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}"
export SINGLE_WISE_DPO_NNODES="${SINGLE_WISE_DPO_NNODES:-1}"
export SINGLE_WISE_DPO_N_GPUS_PER_NODE="${SINGLE_WISE_DPO_N_GPUS_PER_NODE:-8}"

# Ray and compiler cache defaults come from common.py.
mkdir -p "${TMPDIR}" "${RAY_TMPDIR}" "${TORCHINDUCTOR_CACHE_DIR}" "${TRITON_CACHE_DIR}" "${VLLM_CACHE_ROOT}"

export SINGLE_WISE_DPO_INPUT_VARIANT="${SINGLE_WISE_DPO_INPUT_VARIANT:-click_hist}"
export SINGLE_WISE_DPO_SAMPLE_VARIANT="${SINGLE_WISE_DPO_SAMPLE_VARIANT:-all}"
export SINGLE_WISE_DPO_AUTO_PRECOMPUTE_REFERENCE_LOGPS="${SINGLE_WISE_DPO_AUTO_PRECOMPUTE_REFERENCE_LOGPS:-false}"
export SINGLE_WISE_DPO_REFERENCE_FREE="${SINGLE_WISE_DPO_REFERENCE_FREE:-true}"
export SINGLE_WISE_DPO_REFERENCE_MODEL_DIR="${SINGLE_WISE_DPO_REFERENCE_MODEL_DIR:-}"
export SINGLE_WISE_DPO_AVERAGE_LOG_PROB="${SINGLE_WISE_DPO_AVERAGE_LOG_PROB:-true}"
export SINGLE_WISE_DPO_SEED="${SINGLE_WISE_DPO_SEED:-42}"
if [[ -z "${SINGLE_WISE_DPO_APPLY_CHAT_TEMPLATE_KWARGS:-}" ]]; then
  export SINGLE_WISE_DPO_APPLY_CHAT_TEMPLATE_KWARGS='{enable_thinking:false}'
fi
export POINTWISE_DPO_LOSS_TYPE="${POINTWISE_DPO_LOSS_TYPE:-prospect_dpo}"

# Final feedback-weight configuration validated by
# reference_free_paper_weight_sweeps/paper_sigmoid_20260811/trial_01_mean_match.
# The only supported transforms are α(s)=κ₊sigmoid(s) and λ(p)=κ₋sigmoid(p).
# Feedback weighting can be disabled while retaining this same sigmoid loss.
export SINGLE_WISE_DPO_BETA="${SINGLE_WISE_DPO_BETA:-0.1}"
if [[ "${POINTWISE_DPO_LOSS_TYPE,,}" == "prospect_dpo" ]]; then
  export SINGLE_WISE_DPO_POSITIVE_KAPPA="${SINGLE_WISE_DPO_POSITIVE_KAPPA:-3.5}"
  export SINGLE_WISE_DPO_NEGATIVE_KAPPA="${SINGLE_WISE_DPO_NEGATIVE_KAPPA:-1.50}"
  export SINGLE_WISE_DPO_USE_FEEDBACK_WEIGHTS="${SINGLE_WISE_DPO_USE_FEEDBACK_WEIGHTS:-true}"
fi

export SINGLE_WISE_DPO_ACTOR_LR="${SINGLE_WISE_DPO_ACTOR_LR:-${PENS_LR}}"
export SINGLE_WISE_DPO_ACTOR_LR_SCHEDULER_TYPE="${SINGLE_WISE_DPO_ACTOR_LR_SCHEDULER_TYPE:-constant}"
export SINGLE_WISE_DPO_ACTOR_LR_WARMUP_STEPS="${SINGLE_WISE_DPO_ACTOR_LR_WARMUP_STEPS:-0}"
export SINGLE_WISE_DPO_ACTOR_LR_WARMUP_STEPS_RATIO="${SINGLE_WISE_DPO_ACTOR_LR_WARMUP_STEPS_RATIO:-0.0}"
export SINGLE_WISE_DPO_ACTOR_LR_MIN_RATIO="${SINGLE_WISE_DPO_ACTOR_LR_MIN_RATIO:-0.0}"
export SINGLE_WISE_DPO_ACTOR_LR_NUM_CYCLES="${SINGLE_WISE_DPO_ACTOR_LR_NUM_CYCLES:-0.5}"
export SINGLE_WISE_DPO_ACTOR_WEIGHT_DECAY="${SINGLE_WISE_DPO_ACTOR_WEIGHT_DECAY:-0.01}"

export SINGLE_WISE_DPO_USE_LORA="${SINGLE_WISE_DPO_USE_LORA:-true}"
export SINGLE_WISE_DPO_LORA_RANK="${SINGLE_WISE_DPO_LORA_RANK:-64}"
export SINGLE_WISE_DPO_LORA_ALPHA="${SINGLE_WISE_DPO_LORA_ALPHA:-128}"
export SINGLE_WISE_DPO_LORA_TARGET_MODULES="${SINGLE_WISE_DPO_LORA_TARGET_MODULES:-[q_proj,k_proj,v_proj,o_proj]}"
export SINGLE_WISE_DPO_MODEL_DTYPE="${SINGLE_WISE_DPO_MODEL_DTYPE:-bf16}"
export SINGLE_WISE_DPO_ATTN_IMPLEMENTATION="${SINGLE_WISE_DPO_ATTN_IMPLEMENTATION:-flash_attention_2}"
export SINGLE_WISE_DPO_USE_REMOVE_PADDING="${SINGLE_WISE_DPO_USE_REMOVE_PADDING:-false}"
export SINGLE_WISE_DPO_ALLOW_UNSUPPORTED_REMOVE_PADDING="${SINGLE_WISE_DPO_ALLOW_UNSUPPORTED_REMOVE_PADDING:-true}"

export SINGLE_WISE_DPO_TRAIN_BATCH_SIZE="${SINGLE_WISE_DPO_TRAIN_BATCH_SIZE:-128}"
export SINGLE_WISE_DPO_MICRO_BATCH_SIZE="${SINGLE_WISE_DPO_MICRO_BATCH_SIZE:-4}"
export SINGLE_WISE_DPO_USE_DYNAMIC_BSZ="${SINGLE_WISE_DPO_USE_DYNAMIC_BSZ:-false}"
export SINGLE_WISE_DPO_MAX_PROMPT_LENGTH="${SINGLE_WISE_DPO_MAX_PROMPT_LENGTH:-8192}"
export SINGLE_WISE_DPO_MAX_RESPONSE_LENGTH="${SINGLE_WISE_DPO_MAX_RESPONSE_LENGTH:-48}"
export SINGLE_WISE_DPO_PROMPT_TRUNCATION="${SINGLE_WISE_DPO_PROMPT_TRUNCATION:-right}"
export SINGLE_WISE_DPO_DATALOADER_NUM_WORKERS="${SINGLE_WISE_DPO_DATALOADER_NUM_WORKERS:-8}"
export SINGLE_WISE_DPO_USE_LENGTH_BUCKET_SAMPLER="${SINGLE_WISE_DPO_USE_LENGTH_BUCKET_SAMPLER:-true}"
export SINGLE_WISE_DPO_LENGTH_BUCKET_SIZE_MULTIPLIER="${SINGLE_WISE_DPO_LENGTH_BUCKET_SIZE_MULTIPLIER:-50}"
export SINGLE_WISE_DPO_LENGTH_ESTIMATION_MODE="${SINGLE_WISE_DPO_LENGTH_ESTIMATION_MODE:-char}"
export SINGLE_WISE_DPO_LENGTH_ESTIMATION_BATCH_SIZE="${SINGLE_WISE_DPO_LENGTH_ESTIMATION_BATCH_SIZE:-2048}"
export SINGLE_WISE_DPO_LENGTH_ESTIMATION_CHARS_PER_TOKEN="${SINGLE_WISE_DPO_LENGTH_ESTIMATION_CHARS_PER_TOKEN:-4.0}"

export SINGLE_WISE_DPO_RESUME_MODE="${SINGLE_WISE_DPO_RESUME_MODE:-auto}"
export SINGLE_WISE_DPO_TOTAL_TRAINING_STEPS="${SINGLE_WISE_DPO_TOTAL_TRAINING_STEPS:-${PENS_TOTAL_TRAINING_STEPS}}"
export SINGLE_WISE_DPO_LOG_FREQ="${SINGLE_WISE_DPO_LOG_FREQ:-1}"
export SINGLE_WISE_DPO_SAVE_FREQ="${SINGLE_WISE_DPO_SAVE_FREQ:-${PENS_EVAL_INTERVAL}}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_INTERVAL="${SINGLE_WISE_DPO_CHECKPOINT_EVAL_INTERVAL:-${PENS_EVAL_INTERVAL}}"
export SINGLE_WISE_DPO_RUN_CHECKPOINT_EVAL="${SINGLE_WISE_DPO_RUN_CHECKPOINT_EVAL:-true}"
export SINGLE_WISE_DPO_KEEP_ONLY_LATEST_ROLLING_CKPT=false
export SINGLE_WISE_DPO_EARLY_STOP_PATIENCE="${SINGLE_WISE_DPO_EARLY_STOP_PATIENCE:-0}"
export SINGLE_WISE_DPO_EARLY_STOP_MIN_DELTA="${SINGLE_WISE_DPO_EARLY_STOP_MIN_DELTA:-0.0005}"
export SINGLE_WISE_DPO_CATASTROPHIC_DROP="${SINGLE_WISE_DPO_CATASTROPHIC_DROP:-1.0}"
export SINGLE_WISE_DPO_MINIMUM_OUTPUT_COVERAGE="${SINGLE_WISE_DPO_MINIMUM_OUTPUT_COVERAGE:-0.0}"
# ROUGE is at most 1.0 and the manager checks strictly greater than target.
# This unreachable target makes the default run evaluate every boundary up to
# the configured final step instead of stopping at the earlier 0.30 goal.
export SINGLE_WISE_DPO_TARGET_ROUGE_1="${SINGLE_WISE_DPO_TARGET_ROUGE_1:-1.0}"
export SINGLE_WISE_DPO_MINIMUM_ROUGE_2="${SINGLE_WISE_DPO_MINIMUM_ROUGE_2:-0.0}"
export SINGLE_WISE_DPO_MINIMUM_ROUGE_L="${SINGLE_WISE_DPO_MINIMUM_ROUGE_L:-0.0}"

# Search/eval comparisons use deterministic greedy generation.
export GEN_TEMPERATURE="${GEN_TEMPERATURE:-0.0}"
export GEN_TOP_P="${GEN_TOP_P:-0.8}"
export GEN_TOP_K="${GEN_TOP_K:-20}"
export GEN_PROMPT_LENGTH="${GEN_PROMPT_LENGTH:-8000}"
export GEN_RESPONSE_LENGTH="${GEN_RESPONSE_LENGTH:-128}"
export GEN_MAX_MODEL_LEN="${GEN_MAX_MODEL_LEN:-8300}"
export GEN_MAX_NUM_SEQS="${GEN_MAX_NUM_SEQS:-32}"
export GEN_REPETITION_PENALTY="${GEN_REPETITION_PENALTY:-1.1}"
export PASS_K="${PASS_K:-1}"
export VLLM_ENABLE_THINKING="${VLLM_ENABLE_THINKING:-false}"

export SINGLE_WISE_DPO_RUN_TIMESTAMP="${SINGLE_WISE_DPO_RUN_TIMESTAMP:-$(date +%Y%m%d_%H%M%S)}"
pens_init_run dpo "$@"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_NNODES="${SINGLE_WISE_DPO_CHECKPOINT_EVAL_NNODES:-1}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_NGPUS_PER_NODE="${SINGLE_WISE_DPO_CHECKPOINT_EVAL_NGPUS_PER_NODE:-8}"
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_GEN_TP="${SINGLE_WISE_DPO_CHECKPOINT_EVAL_GEN_TP:-1}"

# This prompt parquet is generated by prepare_pens_personalized_eval.py from
# pens_eval_utils.py; it requests one bare headline and never a boxed wrapper.
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_PROMPT_FILE="${SINGLE_WISE_DPO_CHECKPOINT_EVAL_PROMPT_FILE:-${PENS_EVAL_PROMPT_FILE}}"
# The prepared parquet includes gold_headlines and is also a scoring reference.
export SINGLE_WISE_DPO_CHECKPOINT_EVAL_TEST_FILE="${SINGLE_WISE_DPO_CHECKPOINT_EVAL_TEST_FILE:-${PENS_EVAL_TEST_FILE}}"
bash recipe/dpo/run/run_single_wise_interleaved_eval.sh "$@"
